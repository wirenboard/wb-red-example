#!/bin/sh
# Проверка реплики для vrrp_script chk_replica_fresh (репликация состояния).
# Узел, который не держит VIP, годен к роли active только при живом канале
# репликации от соседа: на порту 1883 есть установленное соединение с адреса
# соседа, то есть подключён его мост mosquitto. Иначе реплика на этом узле может
# быть устаревшей. Узел с VIP не проверяется: сломанный канал репликации не повод
# отдавать роль. Роль определяется по наличию VIP на интерфейсе, а не по
# retained-топику: после перезагрузки в нём устаревшее значение.
# Адрес соседа берётся из keepalived.conf, поэтому скрипт одинаков на обоих узлах.
#
# Имя интерфейса и виртуальный IP-адрес замените на свои.
IFACE="wlan0"
VIP="192.168.143.115"
if ip addr show "$IFACE" 2>/dev/null | grep -q "$VIP"; then
    exit 0
fi
PEER=$(awk '/unicast_peer/ {f = 1; next} f && /[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+/ {print $1; exit}' /etc/keepalived/keepalived.conf)
[ -n "$PEER" ] || exit 1
ss -tn state established '( sport = :1883 )' 2>/dev/null | grep -q " ${PEER}:[0-9]" || exit 1
exit 0
